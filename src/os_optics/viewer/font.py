def glyph_mask(char: str) -> np.ndarray:
    rows = GLYPHS.get(char, GLYPHS["?"])
    rows = rows + (".....",) * (GLYPH_HEIGHT - len(rows))
    return np.array([[c == "#" for c in row] for row in rows], dtype=bool)


def text_mask(text: str, scale: int) -> np.ndarray:
    """Boolean ink mask of one line of text at an integer pixel scale."""

    if not text:
        return np.zeros((GLYPH_HEIGHT * scale, 1), dtype=bool)
    mask = np.zeros((GLYPH_HEIGHT, GLYPH_ADVANCE * len(text) - 1), dtype=bool)
    for k, char in enumerate(text):
        mask[:, k * GLYPH_ADVANCE:k * GLYPH_ADVANCE + GLYPH_WIDTH] = glyph_mask(char)
    return np.kron(mask, np.ones((scale, scale), dtype=bool))
