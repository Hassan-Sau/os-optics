"""Scalar low-NA focal field of a pupil-plane field and its mask (a spatial light modulator, a phase plate, a set of tilted beams).

``pupil_field(request)`` (``PupilFieldRequestV1``) computes, with no ray tracing and no change to any run, the stages

    illumination -> opening -> mask -> ideal lens -> focal irradiance

and reports the power at every stage, the status of every quantity (``results.quantity``) and, in the common layout of
``irradiance_map``, the focal irradiance a ``detector_response`` reads.

Conventions (``FIELD_CONVENTIONS``). The field is ``U(x, y) exp(-i w t)`` with propagation ``exp(+i k z)``, ``|U|^2`` in W/mm^2. A mask
multiplies ``U`` by ``amplitude exp(+i phase)``, so ``phase = 2 pi x sin(theta) / lambda`` tilts the light toward ``+x``. The pupil lies in
the front focal plane of an ideal thin lens of focal length ``f`` (transmission ``exp(-i k r^2 / (2 f))``), which gives, with no remaining
quadratic phase and no inversion (Goodman, Fourier Optics, section 5.2)::

    U_f(u, v) = 1 / (i lambda f) * Integral U(x, y) exp(-i 2 pi (x u + y v) / (lambda f)) dx dy

up to the constant phase ``exp(i 2 k f)``, which is left out. The integral is the forward FFT (kernel ``exp(-i 2 pi k m / N)``) of the
field on the pupil grid, zero-padded to ``fft_size`` ``(Nx, Ny)``: focal samples lie at ``u_k = k lambda f / (Nx dx)`` for
``k = -Nx/2 .. Nx/2 - 1`` (likewise ``v``), and the half-sample phase of a grid of even size is removed, so phases refer to the centre of
the pupil grid (``x_m = (m - (nx - 1) / 2) dx``).

Pixels. Without ``fill_factor`` the grid samples a continuous pupil: ``dx dy`` weights the sum and the whole transmitted power lies in the
window ``|u| < lambda f / (2 dx)``. With ``fill_factor`` each cell holds one value over an active rectangle ``a_x = dx sqrt(fill)``,
``a_y = dy sqrt(fill)``: the exact transform is the FFT times ``a_x a_y sinc(a_x u / (lambda f)) sinc(a_y v / (lambda f))``, the window holds
the principal diffraction order of the pixel grid and the replicas beyond it (``power.higher_orders_W``) follow from Parseval's theorem
on the continuous field. Light on the inter-pixel gaps is reported (``power.dead_area_W``) and not propagated.

Power. Discrete Parseval, ``Sum |F|^2 / (Nx Ny) = Sum |M|^2`` for every transform, is checked and reported (``parseval_relative_residual``);
``power`` is the ledger from the incident power to the power in the window. A ``device_efficiency`` scales the field by ``sqrt(eta)``; the
remaining ``1 - eta`` of the light is reported (``power.not_delivered_W``) and has no modeled place on the focal plane. Without one, ``device_efficiency`` is ``UNAVAILABLE`` and the focal power is that of an ideal device.

Field. A ``FIELD`` illumination is a sampled complex field on the pupil grid, from a file given with the request (``field_re``, ``field_im``
in sqrt(W/mm^2): what ``os-optics results field --field-out`` writes of a run's sampled-field or speckle source at a plane); its power is
the sum of ``|U|^2`` times the cell area. A file that states model-scope findings of that light (``model_scope_json``, as ``--field-out``
writes them) gives the document its ``model_scope`` and their ESTIMATE, as a handoff beam's do.

Beams. A ``BEAMS`` or ``HANDOFF_BEAMS`` illumination puts one TEM00 field per beam on the pupil, in the convention of ``results handoff``
(a tilt ``exp(i k (l_x (x - x0) + l_y (y - y0)))``, a curvature ``exp(i k r^2 / (2 R))``). A stated beam's radii and curvatures lie along the plane's axes; a handoff
beam's along its own two Gaussian axes, whatever their orientation on the plane (an elliptical beam turned against ``u`` and ``v`` included), with its footprint on the plane. ``COHERENT``:
fields add with their phases and the complex focal field exists; several beams must each state a phase, and one beam alone without one is computed with its constant phase taken
as 0 (``phase_reference`` ``UNDETERMINED_CONSTANT``: no irradiance depends on it). ``INCOHERENT``: irradiances add, one transform per beam, and no focal
phase exists (``coherent_reason`` ``BEAMS_INCOHERENT``); that is the time average over an exposure much longer than the inverse of the beams'
frequency difference. An incoherent sum of handoff beams leaves out the beams no field can be built from (power out of model scope, part taken before the plane, no known
power, not TEM00, not in air) and lists them: ``excluded_beams`` (``path_id``, ``reason``, ``surfaces``, ``spot_uv_mm``, ``power_W``), ``illumination_complete`` false, and, in the
layout a detector reads, ``map_complete`` false with ``untraced_power_W`` (null when one has no known power): each spot is right, the map does not hold all the light. A coherent
sum refuses instead: a field left out could cancel the others.

Spot array. A ``SPOT_ARRAY`` mask is generated by weighted Gerchberg-Saxton iterations (Di Leonardo et al., Opt. Express 15, 1913 (2007)):
``phi = arg Sum_j g_j sqrt(w_j) exp(i (D_j + theta_j))``, ``D_j = 2 pi (x u_j + y v_j) / (lambda f)``; each iteration sets ``theta_j`` to the
phase of the field at spot ``j`` (the pixel envelope included) and raises ``g_j`` where the spot lags its weight. The start is deterministic, a chirp:
``theta_j = 2 pi frac(j^2 phi_golden)``. A start linear in ``j`` is a plane wave of the array, which leaves the iteration chaotic: rounding of 1e-16 grows to a different mask within ten
iterations and between runtimes; from the chirp it stays at the rounding level. ``spots`` reports for each target (and each beam) its focal power within ``radius_mm`` (the Airy radius
``1.22 lambda f / D``, ``D`` the extent of the illuminated pupil; for Gaussian light at least ``1.5 lambda f / (pi w)``), its peak, and ``array``
the efficiency and uniformity ``1 - (max - min) / (max + min)`` of power / weight.

Validity. The scalar paraxial model holds up to a marginal-ray sine (``pupil_na + field_sine``: the pupil's rim, down to ``RIM_INTENSITY_SHARE``
of its peak irradiance, seen from the focus, plus the output grid's corner seen from the lens) of ``SCALAR_SINE_LIMIT``. There ``sin`` and
``tan`` of the marginal ray differ by 2 %, the aplanatic apodization ``sqrt(cos(theta))`` reaches 1 % in amplitude and the longitudinal
field of a linearly polarized pupil holds ``NA^2 / 4 = 1 %`` of the energy. Above it the focal quantities are ``UNAVAILABLE``
(``NA_ABOVE_SCALAR_LIMIT``), ``status`` is ``PARTIAL`` and the pupil stage and its power ledger stay. Polarization, aberrations and the
device's response in time and across its pixels (fringing fields, phase calibration) are not modeled (``not_modeled``). A beam or a target spot beyond the window is refused (``GRID_INVALID``): the grid
cannot represent it. A pixelated ramp beyond the window is what the pixels do, and folds back as the device does.
"""

