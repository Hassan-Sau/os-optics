class PupilFieldError(Exception):
    """A request that is not a valid ``PupilFieldRequestV1``."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code, self.message = code, message


class _Unavailable(Exception):
    def __init__(self, code: str, message: str, **context: Any) -> None:
        super().__init__(message)
        self.code, self.message, self.context = code, message, context


def parse_request(request: Any) -> PupilFieldRequestV1:
    """``request`` as a ``PupilFieldRequestV1``, or ``PupilFieldError`` with what is wrong."""

    if isinstance(request, PupilFieldRequestV1):
        return request
    try:
        return PupilFieldRequestV1.model_validate(request)
    except ValidationError as exc:
        problems = "; ".join(f"{'.'.join(str(p) for p in e['loc']) or 'request'}: {e['msg']}" for e in exc.errors(include_url=False))
        raise PupilFieldError(PUPIL_FIELD_INVALID, problems) from None


def _refusal(code: str, message: str, **context: Any) -> dict[str, Any]:
    return {"status": UNAVAILABLE, "schema": PUPIL_FIELD_SCHEMA, "schema_version": PUPIL_FIELD_SCHEMA_VERSION, "reason": code, "message": message, **context}


def _next_power_of_two(value: int) -> int:
    return 1 << max(value - 1, 0).bit_length()


@dataclass(frozen=True)
class HandoffBeam:
    """One TEM00 beam of a handoff document on the pupil plane, with the attributes of ``PupilBeamV1`` and its own transverse
    axes. ``beam_radius_mm`` / ``curvature_radius_mm``: its 1/e^2 radii and wavefront curvature radii along its two Gaussian
    axes; ``axes``: those two axes' components along the plane's ``(u, v)`` (``[[e1.u, e1.v], [e2.u, e2.v]]``: a beam's
    transverse coordinates at a plane point are ``axes`` times its offset from the beam's centre); ``radius_mm``: the footprint
    radii on the plane along those axes (each beam radius over its axis's in-plane length, 1 / cos of the tilt)."""

    label: str
    power_w: float
    beam_radius_mm: tuple[float, float]
    radius_mm: tuple[float, float]
    center_mm: tuple[float, float]
    direction_cosines: tuple[float, float]
    curvature_radius_mm: tuple[float | None, float | None]
    phase_rad: float | None
    axes: tuple[tuple[float, float], tuple[float, float]]


def _unusable(beam: Any, focal_length_mm: float) -> tuple[str, str, dict[str, Any]] | None:
    """Why no field can be built from a handoff beam: ``(code, message, context)``, or ``None`` when one can."""

    label = str(beam["path_id"])
    validity = beam["validity"]
    if validity.get("power_out_of_scope_at"):
        behind = sorted(validity["power_out_of_scope_at"])
        return POWER_OUT_OF_MODEL_SCOPE, power_scope_message(behind, "a field built from it"), {"power_out_of_scope_at": behind}
    if validity.get("power_taken_before_at"):  # (part of the beam is taken before the plane, where is not known: its profile and power are not the light's)
        surfaces = sorted(validity["power_taken_before_at"])
        return POWER_TAKEN_BEFORE_PLANE, taken_before_message(surfaces, "a field built from it"), {"power_taken_before_at": surfaces}
    if beam["power_W"] is None:
        where = {"label": label, "u_mm": focal_length_mm * float(beam["chief_ray"]["direction_uvn"][0]),
                 "v_mm": focal_length_mm * float(beam["chief_ray"]["direction_uvn"][1])}
        return BEAM_POWER_UNKNOWN, "", {"spot_position": where}
    if not validity["tem00_field_applicable"] or beam["gaussian"] is None:
        return BEAM_NOT_TEM00, f"beam {label}: {validity['statement']}", {"beam_parameters": validity["beam_parameters"],
                                                                         "truncated_power_fraction": validity.get("truncated_power_fraction")}
    if abs(float(beam["medium_index"] or 1.0) - 1.0) > AIR_INDEX_TOLERANCE:
        return BEAM_NOT_IN_AIR, f"beam {label} is not in air on this plane; the ideal lens of this model is in air", {}
    return None


def _refuse(unusable: list[tuple[Any, tuple[str, str, dict[str, Any]]]], others: bool) -> _Unavailable:
    """The refusal for beams no field can be built from: the first kind found (power out of model scope, then taken before
    the plane, then unknown power, then the first beam that is not TEM00 or not in air), with every beam of that kind.
    ``others``: usable beams stand beside them, which an incoherent sum would keep."""

    rank = {POWER_OUT_OF_MODEL_SCOPE: 0, POWER_TAKEN_BEFORE_PLANE: 1, BEAM_POWER_UNKNOWN: 2, BEAM_NOT_TEM00: 3, BEAM_NOT_IN_AIR: 3}
    first = min(unusable, key=lambda item: rank[item[1][0]])
    code = first[1][0]
    same = [(beam, why) for beam, why in unusable if why[0] == code]
    path_ids = [str(beam["path_id"]) for beam, _why in same]
    # (coherent fields add with their phases, so a field left out could cancel the others: only an incoherent sum can leave one out)
    leave_out = "" if not others else (f"; composition INCOHERENT builds the field of the other beams and lists the beams left out "
                                       f"({', '.join(str(beam['path_id']) for beam, _why in unusable)}) as excluded")
    if code == POWER_OUT_OF_MODEL_SCOPE:
        behind = sorted({surface for _beam, why in same for surface in why[2]["power_out_of_scope_at"]})
        return _Unavailable(code, power_scope_message(behind, "a field built from it") + leave_out, path_ids=path_ids, power_out_of_scope_at=behind)
    if code == POWER_TAKEN_BEFORE_PLANE:
        surfaces = sorted({surface for _beam, why in same for surface in why[2]["power_taken_before_at"]})
        return _Unavailable(code, taken_before_message(surfaces, "a field built from it") + leave_out, path_ids=path_ids, power_taken_before_at=surfaces)
    if code == BEAM_POWER_UNKNOWN:
        return _Unavailable(code, f"{len(same)} beams reach this plane with a known direction and no known power: state the element's efficiency, or choose other beams "
                                  "with path_ids" + leave_out, spot_positions=[why[2]["spot_position"] for _beam, why in same])
    beam, (code, message, context) = first
    return _Unavailable(code, message + leave_out, path_id=str(beam["path_id"]), **context)


def _excluded_rows(unusable: list[tuple[Any, tuple[str, str, dict[str, Any]]]], focal_length_mm: float) -> list[dict[str, Any]]:
    """One row per handoff beam an incoherent sum leaves out: its path, why, the surfaces behind it, where it would focus and
    its power when the handoff states one."""

    rows = []
    for beam, (code, _message, context) in unusable:
        direction = beam["chief_ray"]["direction_uvn"]
        rows.append({"path_id": str(beam["path_id"]), "reason": code,
                     "surfaces": list(context.get("power_out_of_scope_at") or context.get("power_taken_before_at") or []),
                     "spot_uv_mm": [focal_length_mm * float(direction[0]), focal_length_mm * float(direction[1])],
                     "power_W": beam["power_W"]})
    return rows


def beams_of_handoff(handoff: Any, wavelength_nm: float, path_ids: tuple[str, ...] | None = None, focal_length_mm: float = 0.0,
                     composition: str = "COHERENT") -> tuple[tuple[HandoffBeam, ...], list[dict[str, Any]]]:
    """The TEM00 beams of a ``results handoff`` document at ``wavelength_nm`` (``path_ids``: only these), as pupil beams in the plane's
    ``(u, v)`` coordinates, and the rows of the beams left out.

    A beam no field can be built from: its power is out of model scope (``validity.power_out_of_scope_at``:
    ``POWER_OUT_OF_MODEL_SCOPE``), surfaces take part of it before the plane (``validity.power_taken_before_at``:
    ``POWER_TAKEN_BEFORE_PLANE``), it has a direction and no known power (a grating or an acousto-optic deflector with no stated
    efficiency: ``BEAM_POWER_UNKNOWN``, with where it would focus), it is not TEM00 (``BEAM_NOT_TEM00``) or not in air
    (``BEAM_NOT_IN_AIR``). ``composition`` ``COHERENT``: any such beam is a refusal (its field could cancel the others).
    ``INCOHERENT``: irradiances add, so the field of the usable beams is built and the others are returned as excluded rows
    (``path_id``, ``reason``, ``surfaces``, ``spot_uv_mm``, ``power_W``); with no usable beam the refusal is the same as before."""

    if not isinstance(handoff, dict) or not isinstance(handoff.get("beams"), list):
        raise _Unavailable(HANDOFF_REQUIRED, "this illumination reads the beams of a handoff document ('results handoff RUN --monitor ID'); give one")
    chosen = [beam for beam in handoff["beams"] if abs(float(beam["wavelength_nm"]) - wavelength_nm) <= WAVELENGTH_TOLERANCE_NM
              and (path_ids is None or str(beam["path_id"]) in path_ids)]
    if not chosen:
        raise _Unavailable(NO_BEAMS, f"no beam of {wavelength_nm} nm in the handoff document" + ("" if path_ids is None else f" among path_ids {list(path_ids)}"))
    judged = [(beam, _unusable(beam, focal_length_mm)) for beam in chosen]
    unusable = [(beam, why) for beam, why in judged if why is not None]
    usable = [beam for beam, why in judged if why is None]
    if unusable and (composition == "COHERENT" or not usable):
        raise _refuse(unusable, bool(usable))
    beams = []
    for beam in usable:
        gaussian = beam["gaussian"]
        axis_x, axis_y = gaussian["axis_x_uvn"], gaussian["axis_y_uvn"]
        axes = ((float(axis_x[0]), float(axis_x[1])), (float(axis_y[0]), float(axis_y[1])))
        radii = (float(gaussian["beam_radius_x_mm"]), float(gaussian["beam_radius_y_mm"]))
        direction = beam["chief_ray"]["direction_uvn"]
        # the footprint on the plane: a beam tilted toward one of its axes is wider along it by 1 / cos(tilt), the in-plane length of that axis
        along = tuple(math.hypot(axis[0], axis[1]) for axis in axes)
        beams.append(HandoffBeam(label=str(beam["path_id"]), power_w=float(beam["power_W"]), beam_radius_mm=radii,
                                 radius_mm=(radii[0] / along[0], radii[1] / along[1]),
                                 center_mm=(float(beam["chief_ray"]["uv_mm"][0]), float(beam["chief_ray"]["uv_mm"][1])),
                                 direction_cosines=(float(direction[0]), float(direction[1])),
                                 curvature_radius_mm=(gaussian["curvature_radius_x_mm"], gaussian["curvature_radius_y_mm"]),
                                 phase_rad=beam["phase_rad"], axes=axes))
    return tuple(beams), _excluded_rows(unusable, focal_length_mm)


def check_phases(beams: tuple[Any, ...], coherent: bool) -> str | None:
    """Coherent beams add with their phases: several of them must each state one (``PHASE_NOT_DEFINED`` otherwise). One beam
    alone has the same field under both compositions, up to a constant phase: without a stated phase it is taken as 0 and
    ``UNDETERMINED_CONSTANT`` is returned (the document's ``phase_reference``)."""

    if not coherent or all(beam.phase_rad is not None for beam in beams):
        return None
    if len(beams) == 1:
        return UNDETERMINED_CONSTANT
    without = [beam.label or f"beam {index}" for index, beam in enumerate(beams) if beam.phase_rad is None]
    raise _Unavailable(PHASE_NOT_DEFINED, "COHERENT beams add with their phases; every beam must state phase_rad "
                                          "(a beam behind an ideal or tabulated thin lens, a Faraday rotator or a grating has none in a handoff): "
                                          f"{', '.join(without)} do not. Composition INCOHERENT adds their irradiances and needs none",
                       path_ids=without)


def _aperture(request: PupilFieldRequestV1, xx: np.ndarray, yy: np.ndarray) -> np.ndarray:
    aperture = request.aperture
    if aperture is None:
        return np.ones(xx.shape, dtype=bool)
    if isinstance(aperture, PupilCircleV1):
        return xx * xx + yy * yy <= 0.25 * aperture.diameter_mm * aperture.diameter_mm
    return (np.abs(xx) <= 0.5 * aperture.width_mm) & (np.abs(yy) <= 0.5 * aperture.height_mm)


def _gaussian_irradiance(power_w: float, radius: tuple[float, float], center: tuple[float, float], xx: np.ndarray, yy: np.ndarray) -> np.ndarray:
    dx, dy = xx - center[0], yy - center[1]
    return 2.0 * power_w / (math.pi * radius[0] * radius[1]) * np.exp(-2.0 * (dx * dx / (radius[0] * radius[0]) + dy * dy / (radius[1] * radius[1])))


def _beam_field(beam: Any, k: float, xx: np.ndarray, yy: np.ndarray, coherent: bool) -> np.ndarray:
    """One beam's complex field on the pupil grid (module docstring): a ``PupilBeamV1`` (its radii and curvatures along the
    plane's axes) or a ``HandoffBeam`` (along its own axes ``M``, any orientation). With the beam's transverse coordinates
    ``(x1, x2) = M (x - x0, y - y0)`` the irradiance on the plane is ``2 P / (pi w1 w2) |det M| exp(-2 (x1^2 / w1^2 + x2^2 /
    w2^2))`` (``|det M|``: the cosine of the tilt, the flux through the plane) and the curvature phase ``k (x1^2 / (2 R1) + x2^2 /
    (2 R2))``."""

    axes = getattr(beam, "axes", PLANE_AXES)
    radii = getattr(beam, "beam_radius_mm", beam.radius_mm)
    dx, dy = xx - beam.center_mm[0], yy - beam.center_mm[1]
    x1 = axes[0][0] * dx + axes[0][1] * dy
    x2 = axes[1][0] * dx + axes[1][1] * dy
    flux = abs(axes[0][0] * axes[1][1] - axes[0][1] * axes[1][0])
    irradiance = 2.0 * beam.power_w / (math.pi * radii[0] * radii[1]) * np.exp(-2.0 * (x1 * x1 / (radii[0] * radii[0]) + x2 * x2 / (radii[1] * radii[1]))) * flux
    amplitude = np.sqrt(irradiance)
    phase = k * (beam.direction_cosines[0] * dx + beam.direction_cosines[1] * dy)
    for delta, radius in ((x1, beam.curvature_radius_mm[0]), (x2, beam.curvature_radius_mm[1])):
        if radius is not None:
            phase = phase + k * delta * delta / (2.0 * radius)
    if coherent and beam.phase_rad is not None:
        phase = phase + beam.phase_rad
    return amplitude * np.exp(1j * phase)


def _file_mask(mask: FileMaskV1, mask_files: Any, shape: tuple[int, int]) -> tuple[np.ndarray, np.ndarray | None]:
    data = None if mask_files is None else mask_files.get(mask.file_name)
    if data is None:
        raise _Unavailable(MASK_FILE_MISSING, f"mask file {mask.file_name!r} was not given with the request")
    data = bytes(data)
    digest = hashlib.sha256(data).hexdigest()
    if digest != mask.sha256:
        raise _Unavailable(MASK_FILE_HASH_MISMATCH, f"mask file {mask.file_name!r} has SHA-256 {digest}, the request states {mask.sha256}")
    try:
        arrays = arrays_of(data)
    except ValueError as exc:
        raise _Unavailable(MASK_FILE_INVALID, f"mask file {mask.file_name!r}: {exc}") from None
    phase = arrays.get("phase_rad", arrays.get("array"))
    if phase is None:
        raise _Unavailable(MASK_FILE_INVALID, f"mask file {mask.file_name!r} holds no phase_rad array")
    amplitude = arrays.get("amplitude")
    for name, array in (("phase_rad", phase), ("amplitude", amplitude)):
        if array is None:
            continue
        if array.shape != shape or array.dtype.kind not in "fiu" or not np.isfinite(array).all():
            raise _Unavailable(MASK_FILE_INVALID, f"mask file {mask.file_name!r}: {name} must be finite numbers of shape {list(shape)} (rows, columns), "
                                                  f"not {array.dtype} {list(array.shape)}")
    if amplitude is not None and (amplitude.min() < 0.0 or amplitude.max() > 1.0):
        raise _Unavailable(MASK_FILE_INVALID, f"mask file {mask.file_name!r}: amplitude must lie between 0 and 1")
    return phase.astype(np.float64), None if amplitude is None else amplitude.astype(np.float64)


def _field_file(illumination: FieldIlluminationV1, files: Any, shape: tuple[int, int]) -> tuple[np.ndarray, list[dict[str, Any]]]:
    """The complex field of a ``FIELD`` illumination's file (``field_re`` + i ``field_im``, sqrt(W/mm^2)), checked like a mask file,
    and the model-scope findings of its light the file states (``model_scope_json``: ``results.field.field_npz``)."""

    name = illumination.file_name
    data = None if files is None else files.get(name)
    if data is None:
        raise _Unavailable(MASK_FILE_MISSING, f"field file {name!r} was not given with the request")
    data = bytes(data)
    digest = hashlib.sha256(data).hexdigest()
    if digest != illumination.sha256:
        raise _Unavailable(MASK_FILE_HASH_MISMATCH, f"field file {name!r} has SHA-256 {digest}, the request states {illumination.sha256}")
    try:
        arrays = arrays_of(data)
    except ValueError as exc:
        raise _Unavailable(MASK_FILE_INVALID, f"field file {name!r}: {exc}") from None
    parts = [arrays.get("field_re"), arrays.get("field_im")]
    for part, array in zip(("field_re", "field_im"), parts):
        if array is None or array.shape != shape or array.dtype.kind not in "fiu" or not np.isfinite(array).all():
            raise _Unavailable(MASK_FILE_INVALID, f"field file {name!r}: {part} must be finite numbers of shape {list(shape)} (rows, columns)")
    return parts[0].astype(np.float64) + 1j * parts[1].astype(np.float64), _file_scope(arrays.get("model_scope_json"), name)


def _file_scope(text: Any, name: str) -> list[dict[str, Any]]:
    """The ``model_scope`` list a field file states as JSON text (one text, ``[{code, instance_id, touches, validity}]``), checked."""

    import json

    from ..contracts.basis import ValidityCheck
    from ..validation.quantity_kinds import QuantityKind

    if text is None:
        return []
    try:
        if text.dtype.kind != "U" or text.shape != (1,):
            raise ValueError("it is not one text")
        scope = json.loads(str(text[0]))
        if not isinstance(scope, list):
            raise ValueError("it is not a list")
        for finding in scope:
            if not (isinstance(finding, dict) and isinstance(finding.get("code"), str) and isinstance(finding.get("instance_id"), str)
                    and isinstance(finding.get("touches"), list) and isinstance(finding.get("validity"), list)):
                raise ValueError("each finding is {code, instance_id, touches, validity}")
            for kind in finding["touches"]:
                QuantityKind(kind)
            for check in finding["validity"]:
                ValidityCheck.model_validate(check)
    except (ValueError, TypeError, ValidationError) as exc:
        raise _Unavailable(MASK_FILE_INVALID, f"field file {name!r}: model_scope_json is not a list of model-scope findings: {exc}") from None
    return scope


def _spot_array_phase(mask: SpotArrayMaskV1, amplitude: np.ndarray, x: np.ndarray, y: np.ndarray, scale: float, active: tuple[float, float] | None) -> np.ndarray:
    """The weighted Gerchberg-Saxton phase of a spot array (module docstring). ``scale``: ``lambda f``."""

    u = np.array([s.u_mm for s in mask.spots])
    v = np.array([s.v_mm for s in mask.spots])
    weights = np.sqrt(np.array([s.weight for s in mask.spots]))
    ex = np.exp(2j * math.pi * np.outer(x, u) / scale)
    ey = np.exp(2j * math.pi * np.outer(y, v) / scale)
    envelope = np.ones(u.shape) if active is None else np.sinc(active[0] * u / scale) * np.sinc(active[1] * v / scale)
    index = np.arange(u.size)
    theta = 2.0 * math.pi * np.mod(index * index * GOLDEN_FRACTION, 1.0)
    gains = np.ones(u.shape)

    def synthesized() -> np.ndarray:
        return np.angle((ey * (gains * weights * np.exp(1j * theta))) @ ex.T)

    phase = synthesized()
    for _ in range(mask.iterations):
        field = amplitude * np.exp(1j * phase)
        at_spots = ((field @ ex.conj()) * ey.conj()).sum(axis=0) * envelope
        reached = np.abs(at_spots) / weights
        mean = float(reached.mean())
        gains = gains * mean / np.maximum(reached, WEIGHT_FLOOR * mean)
        theta = np.angle(at_spots)
        phase = synthesized()
    return phase


def _mask(request: PupilFieldRequestV1, mask_files: Any, illumination_amplitude: np.ndarray, x: np.ndarray, y: np.ndarray, scale: float,
          active: tuple[float, float] | None) -> tuple[np.ndarray | None, np.ndarray | None, dict[str, Any], dict[str, Any]]:
    """``(phase, amplitude, what the reply says of the mask, the quantity)``."""

    mask = request.mask
    if mask is None:
        return None, None, {"kind": None}, modeled("rad", "no mask: the phase of the illumination")
    shape = (y.size, x.size)
    wavelength_mm = request.wavelength_nm * NM_TO_MM
    if isinstance(mask, BlazedRampMaskV1):
        phase = 2.0 * math.pi * (mask.sin_theta[0] * x[None, :] + mask.sin_theta[1] * y[:, None]) / wavelength_mm
        spots = {"steered_uv_mm": [request.focal_length_mm * mask.sin_theta[0], request.focal_length_mm * mask.sin_theta[1]]}
        return phase, None, {"kind": mask.kind, **spots}, modeled("rad", "linear ramp sampled at the pixel centres")
    if isinstance(mask, BinaryGratingMaskV1):
        along = x[None, :] if mask.axis == "X" else y[:, None]
        phase = mask.phase_depth_rad * (np.mod((along - mask.offset_mm) / mask.period_mm, 1.0) < mask.duty_cycle).astype(np.float64)
        pitch = request.sampling.pitch_mm[0 if mask.axis == "X" else 1]
        return np.broadcast_to(phase, shape), None, {"kind": mask.kind, "samples_per_period": mask.period_mm / pitch}, modeled("rad", "binary grating read at the pixel centres")
    if isinstance(mask, SampledMaskV1):
        amplitude = None if mask.amplitude is None else np.array(mask.amplitude, dtype=np.float64)
        if amplitude is not None and (amplitude.min() < 0.0 or amplitude.max() > 1.0):
            raise _Unavailable(MASK_FILE_INVALID, "mask.amplitude must lie between 0 and 1")
        return np.array(mask.phase_rad, dtype=np.float64), amplitude, {"kind": mask.kind}, stated("rad", "the mask of the request", mask.source.model_dump(mode="json"))
    if isinstance(mask, FileMaskV1):
        phase, amplitude = _file_mask(mask, mask_files, shape)
        return phase, amplitude, {"kind": mask.kind, "file_name": mask.file_name, "sha256": mask.sha256}, stated("rad", f"the mask of {mask.file_name}", mask.source.model_dump(mode="json"))
    assert isinstance(mask, SpotArrayMaskV1)
    phase = _spot_array_phase(mask, illumination_amplitude, x, y, scale, active)
    return phase, None, {"kind": mask.kind, "iterations": mask.iterations, "spot_count": len(mask.spots)}, modeled("rad", "weighted Gerchberg-Saxton phase, generated here")


def _rounded(values: np.ndarray, largest: float | None = None) -> np.ndarray:
    """``values`` rounded to ``MAP_ROUNDING`` of ``largest`` (default: their largest magnitude)."""

    largest = float(np.abs(values).max()) if largest is None else largest
    if largest <= 0.0:
        return values
    step = largest * MAP_ROUNDING
    return np.round(values / step) * step


def _default_half_widths(irradiance: np.ndarray, u: np.ndarray, v: np.ndarray, center: tuple[float, float], spots: list[tuple[float, float]],
                         spot_radius: float) -> tuple[float, float]:
    """The centred box holding ``DEFAULT_ENCLOSED_FRACTION`` of the power on each axis and every spot, shrunk in both axes to the most points a default grid holds."""

    widths = []
    for axis, marginal, c, along in ((u, irradiance.sum(axis=0), center[0], 0), (v, irradiance.sum(axis=1), center[1], 1)):
        reach = np.abs(axis - c)
        order = np.argsort(reach, kind="stable")
        enclosed = np.cumsum(marginal[order])
        total = float(enclosed[-1])
        chosen = float(reach[order][min(int(np.searchsorted(enclosed, (1.0 - 0.5 * (1.0 - DEFAULT_ENCLOSED_FRACTION)) * total)), reach.size - 1)])
        chosen = max(chosen, 2.0 * float(axis[1] - axis[0]))
        for spot in spots:
            chosen = max(chosen, abs(spot[along] - c) + SPOT_MARGIN_RADII * spot_radius)
        widths.append(chosen)
    points = (2.0 * widths[0] / float(u[1] - u[0]) + 1.0) * (2.0 * widths[1] / float(v[1] - v[0]) + 1.0)
    limit = MAX_OUTPUT_POINTS if spots else DEFAULT_MAX_OUTPUT_POINTS
    shrink = 1.0 if points <= limit else math.sqrt(limit / points)
    return shrink * widths[0], shrink * widths[1]


def _crop_window(axis: np.ndarray, center: float, half: float) -> tuple[int, int]:
    """The index range ``[first, last)`` of the axis points within ``half`` of ``center``."""

    step = float(axis[1] - axis[0])
    first = int(max(math.ceil((center - half - axis[0]) / step - INDEX_TOLERANCE), 0))
    last = int(min(math.floor((center + half - axis[0]) / step + INDEX_TOLERANCE) + 1, axis.size))
    return first, last


def _spot_rows(targets: list[dict[str, Any]], irradiance: np.ndarray, u: np.ndarray, v: np.ndarray, radius: float, cell: float, incident_w: float) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Per target its power within the Airy radius and its peak, and the array's efficiency and uniformity."""

    rows = []
    for target in targets:
        i_low, i_high = np.searchsorted(u, target["u_mm"] - radius), np.searchsorted(u, target["u_mm"] + radius)
        j_low, j_high = np.searchsorted(v, target["v_mm"] - radius), np.searchsorted(v, target["v_mm"] + radius)
        patch = irradiance[j_low:j_high, i_low:i_high]
        uu, vv = np.meshgrid(u[i_low:i_high], v[j_low:j_high])
        inside = (uu - target["u_mm"]) ** 2 + (vv - target["v_mm"]) ** 2 <= radius * radius
        power = float(patch[inside].sum()) * cell
        peak = float(patch[inside].max()) if inside.any() else 0.0
        rows.append({**target, "power_W": power, "peak_W_per_mm2": peak, "radius_mm": radius})
    relative = np.array([row["power_W"] / row["weight"] for row in rows])
    peaks = np.array([row["peak_W_per_mm2"] / row["weight"] for row in rows])

    def uniformity(values: np.ndarray) -> float | None:
        spread = float(values.max() + values.min())
        return None if spread <= 0.0 else 1.0 - float(values.max() - values.min()) / spread

    array = {"spot_count": len(rows), "power_W": math.fsum(row["power_W"] for row in rows), "efficiency": math.fsum(row["power_W"] for row in rows) / incident_w,
             "uniformity_power": uniformity(relative), "uniformity_peak": uniformity(peaks),
             "std_over_mean_power": None if relative.mean() <= 0.0 else float(relative.std() / relative.mean())}
    return rows, array


def pupil_field(request: Any, mask_files: Any = None, handoff: Any = None) -> dict[str, Any]:
    """The focal field of a pupil-plane field and its mask (module docstring). ``mask_files``: ``{file name: bytes}`` of a ``FILE`` mask;
    ``handoff``: the ``results handoff`` document of a ``HANDOFF_BEAMS`` illumination.

    ``status``: ``OK`` (the focal stage is available), ``PARTIAL`` (above the validity limit: the pupil stage and the power ledger stay,
    the focal quantities are ``UNAVAILABLE``) or ``UNAVAILABLE`` with a ``reason`` (no field can be built from the inputs)."""

    parsed = parse_request(request)
    try:
        return _pupil_field(parsed, mask_files, handoff)
    except _Unavailable as exc:
        return _refusal(exc.code, exc.message, **exc.context)


def _pupil_field(request: PupilFieldRequestV1, mask_files: Any, handoff: Any) -> dict[str, Any]:
    wavelength_mm, f = request.wavelength_nm * NM_TO_MM, request.focal_length_mm
    k = 2.0 * math.pi / wavelength_mm
    scale = wavelength_mm * f
    sampling = request.sampling
    nx, ny = sampling.pixel_count
    dx, dy = sampling.pitch_mm
    x = (np.arange(nx) - 0.5 * (nx - 1)) * dx
    y = (np.arange(ny) - 0.5 * (ny - 1)) * dy
    xx, yy = np.meshgrid(x, y)
    inside = _aperture(request, xx, yy)
    cell = dx * dy
    fill = sampling.fill_factor
    active = None if fill is None else (dx * math.sqrt(fill), dy * math.sqrt(fill))
    weight_x, weight_y = (dx, dy) if active is None else active
    pixel_area = weight_x * weight_y

    # the illumination: fields on the pupil grid, one per independent beam, with the opening applied
    illumination = request.illumination
    coherent_beams = True
    gaussian_radius = None
    spot_targets: list[dict[str, Any]] = []
    excluded: list[dict[str, Any]] = []
    #: (the model-scope findings of the handoff beams, or the field file, the field is built from: ``handoff.mark_document``)
    scope: list[dict[str, Any]] = []
    phase_reference = None
    if isinstance(illumination, UniformIlluminationV1):
        count = int(inside.sum())
        if count == 0:
            raise _Unavailable(NO_LIGHT, "no grid point lies inside the opening")
        incident = illumination.power_w
        fields = [np.where(inside, math.sqrt(incident / (count * cell)), 0.0).astype(np.complex128)]
    elif isinstance(illumination, GaussianIlluminationV1):
        incident = illumination.power_w
        amplitude = np.sqrt(_gaussian_irradiance(incident, illumination.radius_mm, illumination.center_mm, xx, yy))
        fields = [np.where(inside, amplitude, 0.0).astype(np.complex128)]
        gaussian_radius = min(illumination.radius_mm)
    elif isinstance(illumination, FieldIlluminationV1):
        given, scope = _field_file(illumination, mask_files, (ny, nx))
        incident = float(np.sum(np.abs(given) ** 2)) * cell
        fields = [np.where(inside, given, 0.0).astype(np.complex128)]
    else:
        if isinstance(illumination, BeamsIlluminationV1):
            beams: tuple[Any, ...] = illumination.beams
        else:
            assert isinstance(illumination, HandoffBeamsIlluminationV1)
            beams, excluded = beams_of_handoff(handoff, request.wavelength_nm, illumination.path_ids, f, illumination.composition)
            scope = handoff_scope(handoff, [beam.label for beam in beams])
        coherent_beams = illumination.composition == "COHERENT"
        phase_reference = check_phases(beams, coherent_beams)
        incident = math.fsum(beam.power_w for beam in beams)
        per_beam = [_beam_field(beam, k, xx, yy, coherent_beams) * inside for beam in beams]
        fields = [sum(per_beam[1:], per_beam[0])] if coherent_beams else per_beam
        gaussian_radius = min(min(beam.radius_mm) for beam in beams)
        spot_targets = [{"label": beam.label, "u_mm": f * beam.direction_cosines[0], "v_mm": f * beam.direction_cosines[1], "weight": beam.power_w} for beam in beams]
    pupil_irradiance = sum(np.abs(field) ** 2 for field in fields)
    on_pupil = float(pupil_irradiance.sum()) * cell
    peak = float(pupil_irradiance.max())
    if peak <= 0.0:
        raise _Unavailable(NO_LIGHT, "no light on the pupil grid: the opening and the illumination do not overlap")

    # the sampling of the focal plane: a beam or a target beyond the window would fold back into it
    window = (0.5 * scale / dx, 0.5 * scale / dy)
    targets = list(spot_targets)
    if isinstance(request.mask, SpotArrayMaskV1):
        targets += [{"u_mm": s.u_mm, "v_mm": s.v_mm} for s in request.mask.spots]
    elif isinstance(request.mask, BlazedRampMaskV1) and active is None:
        targets.append({"u_mm": f * request.mask.sin_theta[0], "v_mm": f * request.mask.sin_theta[1]})
    if any(abs(t["u_mm"]) >= window[0] or abs(t["v_mm"]) >= window[1] for t in targets):
        raise _Unavailable(GRID_INVALID, f"a spot lies beyond the window |u| < {window[0]}, |v| < {window[1]} mm of this grid (half of lambda f / pitch) and would fold back into "
                                         "it; use a smaller pitch_mm or smaller deflections")
    lit = pupil_irradiance >= RIM_INTENSITY_SHARE * peak
    rim_mm = float(np.sqrt(xx[lit] ** 2 + yy[lit] ** 2).max())
    columns, rows = np.nonzero(lit.any(axis=0))[0], np.nonzero(lit.any(axis=1))[0]
    spans = (int(columns[-1] - columns[0]) + 1, int(rows[-1] - rows[0]) + 1)
    fft_x, fft_y = sampling.fft_size or (_next_power_of_two(2 * nx), _next_power_of_two(2 * ny))
    if fft_x > MAX_FFT_SAMPLES or fft_y > MAX_FFT_SAMPLES:
        raise _Unavailable(GRID_INVALID, f"pixel_count {nx} x {ny} needs a transform of {fft_x} x {fft_y} points; the most is {MAX_FFT_SAMPLES} per axis: "
                                         "state fft_size with at least twice the illuminated span, or use a smaller grid")
    if fft_x < 2 * spans[0] or fft_y < 2 * spans[1]:
        raise _Unavailable(GRID_INVALID, f"fft_size {fft_x} x {fft_y} does not sample the focal irradiance fully: the illuminated span is {spans[0]} x "
                                         f"{spans[1]} points and fft_size must be at least twice it")
    du, dv = scale / (fft_x * dx), scale / (fft_y * dy)
    u = (np.arange(fft_x) - fft_x // 2) * du
    v = (np.arange(fft_y) - fft_y // 2) * dv
    focal_cell = du * dv
    spot_radius = AIRY_RADIUS_FACTOR * scale / (2.0 * max(rim_mm, 0.5 * min(dx, dy)))
    if gaussian_radius is not None:
        spot_radius = max(spot_radius, GAUSSIAN_SPOT_RADII * scale / (math.pi * gaussian_radius))

    # the mask
    mask_amplitude_source = np.sqrt(pupil_irradiance)
    phase, mask_amplitude, mask_doc, mask_quantity = _mask(request, mask_files, mask_amplitude_source, x, y, scale, active)
    if isinstance(request.mask, SpotArrayMaskV1):
        spot_targets = [{"label": f"spot {index}", "u_mm": s.u_mm, "v_mm": s.v_mm, "weight": s.weight} for index, s in enumerate(request.mask.spots)]
    transmission: Any = 1.0
    if phase is not None:
        transmission = np.exp(1j * phase) if mask_amplitude is None else mask_amplitude * np.exp(1j * phase)

    # the transform of each independent field, with the pixel envelope and the half-sample phase of the grid
    fx, fy = u / scale, v / scale
    envelope_x = np.ones(fft_x) if active is None else np.sinc(active[0] * fx)
    envelope_y = np.ones(fft_y) if active is None else np.sinc(active[1] * fy)
    center_x = np.exp(-2j * math.pi * fx * x[0])
    center_y = np.exp(-2j * math.pi * fy * y[0])
    efficiency = None if request.device_efficiency is None else request.device_efficiency.value
    prefactor = weight_x * weight_y / scale * (1.0 if efficiency is None else math.sqrt(efficiency))
    focal_irradiance = np.zeros((fft_y, fft_x))
    focal_field = None
    after_mask = 0.0
    parseval_worst = 0.0
    for field in fields:
        masked = field * transmission
        squared = float((np.abs(masked) ** 2).sum())
        after_mask += squared * pixel_area
        transform = np.fft.fftshift(np.fft.fft2(masked, s=(fft_y, fft_x)))
        if squared > 0.0:
            parseval_worst = max(parseval_worst, abs(float((np.abs(transform) ** 2).sum()) / (fft_x * fft_y) - squared) / squared)
        amplitude_map = prefactor * transform * envelope_y[:, None] * envelope_x[None, :]
        focal_irradiance += (amplitude_map.real * amplitude_map.real + amplitude_map.imag * amplitude_map.imag)
        if coherent_beams:
            focal_field = -1j * amplitude_map * center_y[:, None] * center_x[None, :]
    window_power = float(focal_irradiance.sum()) * focal_cell

    # the power ledger
    active_power = on_pupil if fill is None else on_pupil * fill
    delivered = after_mask if efficiency is None else after_mask * efficiency
    ledger = {
        "incident_W": incident, "on_pupil_W": on_pupil, "clipped_W": max(incident - on_pupil, 0.0),
        "dead_area_W": on_pupil - active_power, "active_W": active_power, "absorbed_by_mask_W": max(active_power - after_mask, 0.0), "after_mask_W": after_mask,
        "not_delivered_W": after_mask - delivered, "delivered_W": delivered,
        "window_W": window_power, "higher_orders_W": max(delivered - window_power, 0.0),
        "window_half_widths_mm": list(window),
        "parseval_relative_residual": parseval_worst,
    }

    # the output grid and the model's domain
    center = request.output.center_uv_mm
    half = request.output.half_extent_mm
    if half is None:
        half = _default_half_widths(focal_irradiance, u, v, center, [(t["u_mm"], t["v_mm"]) for t in spot_targets], spot_radius)
    elif not all(h > 0.0 for h in half):
        raise _Unavailable(GRID_INVALID, "output.half_extent_mm must be two positive numbers")
    first_u, last_u = _crop_window(u, center[0], half[0])
    first_v, last_v = _crop_window(v, center[1], half[1])
    if last_u - first_u < 2 or last_v - first_v < 2:
        raise _Unavailable(GRID_INVALID, f"the output grid holds fewer than 2 points per axis: the focal step is {du} x {dv} mm and the window's half "
                                         f"widths are {0.5 * scale / dx} x {0.5 * scale / dy} mm")
    if (last_u - first_u) * (last_v - first_v) > MAX_OUTPUT_POINTS:
        raise _Unavailable(GRID_INVALID, f"the output grid holds {last_u - first_u} x {last_v - first_v} points; the most is {MAX_OUTPUT_POINTS} in all: use a smaller half_extent_mm")
    grid_u, grid_v = u[first_u:last_u], v[first_v:last_v]
    pupil_na = rim_mm / f
    field_sine = math.hypot(max(abs(float(grid_u[0])), abs(float(grid_u[-1]))), max(abs(float(grid_v[0])), abs(float(grid_v[-1])))) / f
    marginal = pupil_na + field_sine
    in_domain = marginal <= SCALAR_SINE_LIMIT
    validity = {"pupil_na": pupil_na, "field_sine": field_sine, "marginal_ray_sine": marginal, "limit": SCALAR_SINE_LIMIT, "in_domain": in_domain, "pupil_rim_mm": rim_mm,
                "statement": ("At the limit sin and tan of the marginal ray differ by 2 %, the aplanatic apodization reaches 1 % in amplitude and the longitudinal "
                              "field of a linearly polarized pupil holds 1 % of the energy.")}
    device = (stated(None, efficiency, request.device_efficiency.source.model_dump(mode="json")) if request.device_efficiency is not None
              else unavailable(None, PARAMETER_NOT_STATED, "device_efficiency is not stated: the focal power is that of an ideal device", ["device_efficiency"]))
    quantities: dict[str, Any] = {
        "pupil_power_W": modeled("W", "the illumination over the grid points inside the opening", value=on_pupil),
        "mask_phase": mask_quantity,
        "device_efficiency": device,
        "polarization": unavailable(None, SCALAR_MODEL, "the field is scalar"),
    }
    doc: dict[str, Any] = {
        "status": "OK" if in_domain else "PARTIAL", "schema": PUPIL_FIELD_SCHEMA, "schema_version": PUPIL_FIELD_SCHEMA_VERSION, "model": FOCAL_MODEL,
        "wavelength_nm": request.wavelength_nm, "focal_length_mm": f, "conventions": dict(FIELD_CONVENTIONS), "not_modeled": list(NOT_MODELED),
        "pupil": {"pixel_count": [nx, ny], "pitch_mm": [dx, dy], "fill_factor": fill, "fft_size": [fft_x, fft_y], "illuminated_span_samples": list(spans),
                  "x_mm": [float(x[0]), float(x[-1])], "y_mm": [float(y[0]), float(y[-1])]},
        "mask": mask_doc, "power": ledger, "validity": validity, "quantities": quantities,
    }
    if request.output.include_mask and phase is not None:
        doc["mask"] = {**doc["mask"], "phase_rad": np.broadcast_to(phase, (ny, nx)).tolist()}
    if phase_reference is not None:
        doc["phase_reference"] = phase_reference
    if excluded:
        # (an incoherent sum that leaves beams out: each spot of the map is right, the map does not hold all the plane's light;
        # in the layout a detector reads -- results.irradiance)
        bounds = [row["power_W"] for row in excluded]
        left_out = None if any(power is None for power in bounds) else math.fsum(bounds)
        doc.update(illumination_complete=False, excluded_beams=excluded, map_complete=False, untraced_power_W=left_out,
                   untraced_fraction=None if left_out is None else left_out / incident, interference_open=False)
    if not in_domain:
        message = (f"the marginal-ray sine {marginal:.3f} is above the scalar model's limit {SCALAR_SINE_LIMIT}; use a longer focal length, a smaller "
                   "pupil or a smaller output grid, or 'results focal-field' (the vector focal field of an ideal objective) for this focus")
        for name, unit in (("focal_irradiance", "W/mm^2"), ("focal_phase", "rad")):
            quantities[name] = unavailable(unit, NA_ABOVE_SCALAR_LIMIT, message)
        doc.update(reason=NA_ABOVE_SCALAR_LIMIT, message=message)
        return mark_document(doc, scope, PUPIL_UNLIT)

    # the focal stage, in the layout of irradiance_map
    irradiance_map = _rounded(focal_irradiance)
    grid_map = irradiance_map[first_v:last_v, first_u:last_u]
    grid_power = float(grid_map.sum()) * focal_cell
    quantities["focal_irradiance"] = modeled("W/mm^2", "|U_f|^2 on the focal grid" if coherent_beams else "sum of each beam's |U_f|^2 on the focal grid")
    if coherent_beams:
        quantities["focal_phase"] = modeled("rad", "the phase of U_f: see conventions; return it with output.include_field")
    else:
        quantities["focal_phase"] = unavailable("rad", BEAMS_INCOHERENT, "independent beams have no common focal phase")
    map_list = grid_map.tolist()
    doc.update({
        "composition": "COHERENT" if coherent_beams else "INCOHERENT_SUM",
        "coherent_W_per_mm2": map_list if coherent_beams else None, "incoherent_W_per_mm2": None if coherent_beams else map_list,
        "coherent_reason": None if coherent_beams else BEAMS_INCOHERENT,
        "grid": {"u_mm": grid_u.tolist(), "v_mm": grid_v.tolist(), "shape": [int(last_v - first_v), int(last_u - first_u)], "order": ORDER,
                 "center_uv_mm": [center[0], center[1]]},
        "sampling": {"grid_step_mm": [du, dv]},
        "grid_power_coherent_W": grid_power if coherent_beams else None, "grid_power_incoherent_W": None if coherent_beams else grid_power,
        "power_outside_grid_W": max(window_power - grid_power, 0.0),
    })
    if spot_targets:
        doc["spots"], doc["array"] = _spot_rows(spot_targets, irradiance_map, u, v, spot_radius, focal_cell, incident)
    if request.output.include_field and focal_field is not None:
        cropped = focal_field[first_v:last_v, first_u:last_u]
        # one scale for both parts: a part that is only the transform's rounding noise rounds to 0, not to a pattern of its own
        magnitude = float(np.abs(cropped).max())
        doc["field_sqrt_W_per_mm2"] = {"re": _rounded(cropped.real, magnitude).tolist(), "im": _rounded(cropped.imag, magnitude).tolist()}
    return mark_document(doc, scope, PUPIL_UNLIT)


