"""Regenerate the machine-derived parts of the docs.

    python docs/engine/generate_docs.py

Currently: the tolerance table of docs/engine/NUMERICAL_CONVENTIONS.md (between the BEGIN/END markers), generated from NumericalConfig, and
the material finish table of docs/engine/VIEWER_MATERIALS.md, generated from the GLB's finishes, and the table of metrics a run does not
evaluate in section P9 of docs/engine/PHYSICS_SCOPE.md, generated from validation/scope.py, so the documentation cannot drift from the code
(tests/test_docs_in_sync.py enforces this)."""

from __future__ import annotations

from pathlib import Path

from os_optics import NumericalConfig
from os_optics.optical_view.glb import MATERIAL_FINISHES
from os_optics.validation.scope import ANALYSIS_METRIC_ROUTES, CAVITY_METRICS, OUT_OF_SCOPE_METRICS

DOC = Path(__file__).resolve().parent / "NUMERICAL_CONVENTIONS.md"
BEGIN = "<!-- BEGIN TOLERANCES (generated by docs/engine/generate_docs.py; do not edit) -->"
END = "<!-- END TOLERANCES -->"
MATERIALS_DOC = DOC.parent / "VIEWER_MATERIALS.md"
MATERIALS_BEGIN = "<!-- BEGIN MATERIAL FINISHES (generated by docs/engine/generate_docs.py; do not edit) -->"
MATERIALS_END = "<!-- END MATERIAL FINISHES -->"
SCOPE_DOC = DOC.parent / "PHYSICS_SCOPE.md"
SCOPE_BEGIN = "<!-- BEGIN SCOPE METRICS (generated by docs/engine/generate_docs.py; do not edit) -->"
SCOPE_END = "<!-- END SCOPE METRICS -->"


def tolerance_table() -> str:
    rows = ["| Field | Default | Meaning / reason |", "|---|---|---|"]
    for name, field in NumericalConfig.model_fields.items():
        if name == "config_version":
            continue
        default = field.default
        rows.append(f"| `{name}` | `{default!r}` | {field.description} |")
    return "\n".join(rows)


def render(text: str) -> str:
    start, stop = text.index(BEGIN), text.index(END)
    return text[: start + len(BEGIN)] + "\n\n" + tolerance_table() + "\n\n" + text[stop:]


def material_table() -> str:
    rows = ["| Material | Metallic | Roughness | Transmission |", "|---|---|---|---|"]
    rows += [f"| `{name}` | {f.metallic} | {f.roughness} | {f.transmission} |" for name, f in MATERIAL_FINISHES.items()]
    return "\n".join(rows)


def render_materials(text: str) -> str:
    start, stop = text.index(MATERIALS_BEGIN), text.index(MATERIALS_END)
    return text[: start + len(MATERIALS_BEGIN)] + "\n\n" + material_table() + "\n\n" + text[stop:]


def scope_metric_table() -> str:
    rows = ["| Metric | Not modelled, or what computes it |", "|---|---|"]
    rows += [f"| `{name}` | {text.replace('|', '/')} |" for name, text in OUT_OF_SCOPE_METRICS.items()]
    for name, route in ANALYSIS_METRIC_ROUTES.items():
        text = (f"the cavity analysis (`os-optics project cavity`, `os-optics results cavity`), quantity `{CAVITY_METRICS[name]}`"
                if name in CAVITY_METRICS else route.replace("|", "/"))
        rows.append(f"| `{name}` | {text} |")
    return "\n".join(rows)


def render_scope(text: str) -> str:
    start, stop = text.index(SCOPE_BEGIN), text.index(SCOPE_END)
    return text[: start + len(SCOPE_BEGIN)] + "\n\n" + scope_metric_table() + "\n\n" + text[stop:]


def main() -> None:
    for doc, renderer in ((DOC, render), (MATERIALS_DOC, render_materials), (SCOPE_DOC, render_scope)):
        doc.write_text(renderer(doc.read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
        print("updated", doc)


if __name__ == "__main__":
    main()
